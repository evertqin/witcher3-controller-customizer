"""Prepare a fingerprint-checked Phase 1.1 runtime candidate; no live writes."""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

from full_schemes import SchemeError, build_appendix, checked_source, digital_pad, expand_lineage


def replace_once(text, old, new):
    if text.count(old) != 1:
        raise SchemeError("Runtime baseline changed; review transform before staging")
    return text.replace(old, new, 1)


def generated_helpers(repo, native_input, aliases):
    manifest = json.loads((repo / "data/schemes/manifest.json").read_text(encoding="utf-8"))
    schemes = manifest["schemes"]
    unique_aliases = list({a["alias"]: a for a in aliases}.values())
    contexts = sorted({item["canonical"] for item in aliases})
    profiles = {
        scheme["id"]: expand_lineage(checked_source(
            native_input if scheme["id"] == "vanilla" else repo / scheme["fixture"],
            scheme["source_sha256"])) for scheme in schemes
    }
    ws = ["// Generated by tools/automation/scheme_runtime.py; selection schema 2."]
    ws.extend(f"// {s['id']} SHA256 {s['source_sha256']}" for s in schemes)
    ws.extend(["function CCGeneratedCanonicalContext(contextName : name) : name",
               "{", "    switch (contextName)", "    {"])
    for context in contexts:
        ws.extend(f"        case '{a['alias']}':" for a in unique_aliases if a["canonical"] == context)
        # Recognize old aliases during an explicitly journaled upgrade, too.
        if context in ("BASE_INTERACTIONS_HORSE", "Horse", "Horse_Replacer_Ciri", "ScriptedAction"):
            ws.extend(f"        case 'CC_PROBE_{old}_{context}':" for old in ("Current", "Alt1"))
        ws.append(f"            return '{context}';")
    ws.extend(["    }", "    return contextName;", "}", "",
               "function CCGeneratedResolveContext(baseContext : name, preset : int) : name",
               "{", "    switch (baseContext)", "    {"])
    for context in contexts:
        ws.append(f"        case '{context}':")
        for index, scheme in enumerate(schemes):
            alias = next(a["alias"] for a in aliases if a["canonical"] == context and a["scheme"] == scheme["id"])
            ws.append(f"            if (preset == {index}) {{ return '{alias}'; }}")
        ws.append("            return baseContext;")
    ws.extend(["    }", "    return baseContext;", "}", "",
               "function CCGeneratedCheckContexts() : bool", "{", "    var available : bool;",
               "    available = true;"])
    # Call inspection first so a failure cannot short-circuit subsequent checks.
    ws.extend(f"    available = CCRegisteredContext('{a['alias']}') && available;" for a in unique_aliases)
    ws.extend(["    return available;", "}", "",
               "function CCGeneratedReleaseContextActions(contextName : name)", "{",
               "    switch (CCGeneratedCanonicalContext(contextName))", "    {"])
    release_actions = {}
    for context in contexts:
        counters = [Counter(r.signature for r in profiles[s["id"]][context] if digital_pad(r)) for s in schemes]
        common = counters[0] & counters[1] & counters[2]
        actions = set()
        for scheme, counter in zip(schemes, counters):
            changed = counter - common
            for row in profiles[scheme["id"]][context]:
                if row.signature in changed:
                    match = re.search(r"(?:\(|,)\s*Action=([A-Za-z0-9_]+)(?:,|\))", row.value)
                    if not match:
                        raise SchemeError("Changed controller record lacks a safe native action")
                    actions.add(match[1])
        release_actions[context] = sorted(actions)
        ws.append(f"        case '{context}':")
        ws.extend(f"            theInput.ForceDeactivateAction('{action}');" for action in sorted(actions))
        ws.append("            return;")
    ws.extend(["    }", "}", ""])
    ws.extend(generated_hint_helpers(profiles, contexts))
    old = (repo / "data/schemes/runtime-templates/presetData.ws").read_text(encoding="utf-8")
    tail = old[old.index("function CCGeneratedHorseSpeedMember"):]
    # The two historical Souls helper rows become slots 1 and 2; slot 0 is native.
    tail = tail.replace("preset == 1", "preset == 2").replace("preset == 0", "preset == 1")
    tail = tail.replace('return "Current";', 'return "DarkSoul";').replace('return "Alt1";', 'return "DarkSoul Alt1";')
    tail = replace_once(tail, 'function CCGeneratedPresetName(preset : int) : string\n{',
                        'function CCGeneratedPresetName(preset : int) : string\n{\n    if (preset == 0) { return "Current (original)"; }')
    return "\n".join(ws) + tail, release_actions



def hint_keys(profiles, context, action):
    result = []
    for scheme in profiles:
        keys = []
        for row in profiles[scheme][context]:
            if digital_pad(row) and re.search(r"(?:\(|,)\s*Action=" + re.escape(action) + r"(?:,|\))", row.value):
                if row.key not in keys:
                    keys.append(row.key)
        result.append(keys)
    return result


def generated_hint_helpers(profiles, contexts):
    ws = ["function CCGeneratedPadHintKeys(contextName : name, preset : int, actionName : name, out keys : array<EInputKey>) : bool",
          "{", "    if (preset < 0 || preset > 2) { return false; }",
          "    switch (CCGeneratedCanonicalContext(contextName))", "    {"]
    for context in contexts:
        actions = set()
        for scheme in profiles:
            for row in profiles[scheme][context]:
                if digital_pad(row):
                    match = re.search(r"(?:\(|,)\s*Action=([A-Za-z0-9_]+)(?:,|\))", row.value)
                    if match:
                        actions.add(match[1])
        changed = {action: hint_keys(profiles, context, action) for action in sorted(actions)}
        changed = {action: keys for action, keys in changed.items() if not all(keys[0] == k for k in keys[1:])}
        if not changed:
            continue
        ws.extend([f"        case '{context}':", "            switch (actionName)", "            {"])
        for action, schemes in changed.items():
            ws.extend([f"                case '{action}':", "                    keys.Clear();"])
            for index, keys in enumerate(schemes):
                ws.extend([f"                    if (preset == {index})", "                    {"])
                ws.extend(f"                        keys.PushBack({key});" for key in (keys or ['IK_None']))
                ws.append("                    }")
            ws.append("                    return true;")
        ws.extend(["            }", "            return false;"])
    ws.extend(["    }", "    return false;", "}", ""])
    return ws


def prepare(repo, native_input, personal_text):
    appendix, aliases = build_appendix(repo, native_input, personal_text)
    generated, releases = generated_helpers(repo, native_input, aliases)
    scripts = repo / "data/schemes/runtime-templates"
    baseline = json.loads((repo / "data/schemes/runtime-baseline.json").read_text(encoding="utf-8"))
    if baseline["schema_version"] != 1 or baseline["selection_schema_version"] != 2:
        raise SchemeError("Unsupported runtime baseline")
    for name, digest in baseline["templates_sha256"].items():
        path = (scripts / name).resolve()
        if path.parent != scripts.resolve() or hashlib.sha256(path.read_bytes()).hexdigest() != digest:
            raise SchemeError("Runtime generation template changed; review and repin baseline")
    outputs = {"src/scripts/local/controllerCustomizer/" + p.name: p.read_text(encoding="utf-8")
               for p in scripts.glob("*.ws")}
    if len(outputs) != 8:
        raise SchemeError("Expected eight owned script sources")

    def get(name):
        return outputs["src/scripts/local/controllerCustomizer/" + name + ".ws"]

    def put(name, text):
        outputs["src/scripts/local/controllerCustomizer/" + name + ".ws"] = text

    put("presetData", generated)
    bootstrap = get("bootstrap")
    start = bootstrap.index("    available = CCRegisteredContext(")
    end = bootstrap.index("    theInput.CCProbeSetInspectionContext(original);", start)
    bootstrap = bootstrap[:start] + "    available = CCGeneratedCheckContexts();\n" + bootstrap[end:]
    bootstrap = replace_once(bootstrap, "    theInput.CCRefreshPreset();",
                             "    CCInitializeSchemeSelection();\n    theInput.CCRefreshPreset();")
    put("bootstrap", bootstrap)
    put("contextAdapter", replace_once(get("contextAdapter"),
        "if (preset != 0 && preset != 1)", "if (preset < 0 || preset > 2)"))
    bindings = get("bindings")
    start = bindings.index("function CCProbeReleaseOwnedActions()")
    end = bindings.index("\nexec function ccProbeAction", start)
    bindings = bindings[:start] + "function CCProbeReleaseOwnedActions()\n{\n    if (theInput) { CCGeneratedReleaseContextActions(CCProbeReadRawContext()); }\n}\n" + bindings[end:]
    put("bindings", bindings)

    config = get("config")
    start = config.index("    value = config.GetVarValue(")
    end = config.index("    return -1;", start)
    config = config[:start] + '''    value = config.GetVarValue('ControllerCustomizer', 'Scheme');
    if (value == "0") { return 0; }
    if (value == "1") { return 1; }
    if (value == "2") { return 2; }
''' + config[end:]
    config = replace_once(config, "requested == 0 || requested == 1", "requested == 0 || requested == 1 || requested == 2")
    config = replace_once(config, "    alt = theInput.CCAcceptPreset(1);", "    alt = theInput.CCAcceptPreset(2);")
    # Missing/-1 Scheme means not yet migrated; other invalid values never erase
    # a stored choice. Legacy hidden Preset is read before changing its meaning.
    config += '''
function CCInitializeSchemeSelection()
{
    var config : CInGameConfigWrapper;
    var scheme : string;
    var legacy : string;
    if (!theGame || !theInput) { return; }
    config = theGame.GetInGameConfigWrapper();
    if (!config) { return; }
    // Initialize the unsaved fallback to the user's preferred scheme.
    theInput.CCAcceptPreset(2);
    scheme = config.GetVarValue('ControllerCustomizer', 'Scheme');
    if (scheme != "" && scheme != "-1") { return; }
    legacy = config.GetVarValue('ControllerCustomizer', 'Preset');
    if (legacy == "0") { scheme = "1"; }
    else if (legacy == "1" || legacy == "" || legacy == "-1") { scheme = "2"; }
    else { return; }
    config.SetVarValue('ControllerCustomizer', 'Scheme', scheme);
}
'''
    put("config", config)
    diagram = replace_once(get("diagram"), "if (preset != 0 && preset != 1)", "if (preset != 1 && preset != 2)")
    diagram = replace_once(diagram, "    for (index = 0; index < data.GetLength(); index += 1)",
        "    if (CCDisplayPreset() == 0) { return data; }\n    for (index = 0; index < data.GetLength(); index += 1)")
    put("diagram", diagram)
    contexts = get("contexts")
    contexts = contexts.replace("CC_PROBE_Current_", "CC_SCHEME_DarkSoul_").replace("CC_PROBE_Alt1_", "CC_SCHEME_DarkSoulAlt1_")
    # Normal startup validates the entire bank; the old riding diagnostic still
    # checks its eight representative Souls names independently of global keys.
    put("contexts", contexts)
    menu = ET.parse(scripts / "modControllerCustomizer.xml").getroot()
    variables = menu.find("./Group/VisibleVars")
    original = variables.find("Var[@id='Preset']")
    original.set("visibilityCondition", "hideAlways")
    original.set("value", "-1")
    scheme = ET.Element("Var", {"id": "Scheme", "displayName": "Controller scheme",
        "displayType": "OPTIONS", "tags": "nonLocalized;nonLocalizedName;customNames", "value": "-1"})
    options = ET.SubElement(scheme, "OptionsArray")
    for index, label in enumerate(("Current (original)", "DarkSoul", "DarkSoul Alt1")):
        option = ET.SubElement(options, "Option", {"id": str(index), "displayName": label})
        ET.SubElement(option, "Entry", {"varId": "Scheme", "value": str(index)})
    variables.insert(0, scheme)
    ET.indent(menu, space="  ")
    outputs["src/menu/modControllerCustomizer.xml"] = '<?xml version="1.0" encoding="UTF-8"?>\n' + ET.tostring(menu, encoding="unicode") + "\n"
    outputs["full-scheme-appendix.ini"] = appendix
    outputs["tools/compiler-toolchain.json"] = (repo / "tools/compiler-toolchain.json").read_text(encoding="utf-8-sig")
    receipt = {"schema_version": 1, "selection_schema_version": 2, "aliases": aliases,
        "release_actions": releases, "personal_input_sha256": hashlib.sha256(personal_text.encode("utf-8")).hexdigest(),
        "runtime_installed": False, "runtime_load_verified": False,
        "files": {key: hashlib.sha256(value.encode("utf-8")).hexdigest() for key, value in outputs.items()}}
    return outputs, receipt


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--native-input", type=Path, required=True)
    parser.add_argument("--personal-input", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--check-runtime", action="store_true")
    parser.add_argument("--sync-runtime", action="store_true")
    args = parser.parse_args()
    if args.check_runtime and args.sync_runtime:
        parser.error("Choose check or sync")
    if not args.output and not (args.check_runtime or args.sync_runtime):
        parser.error("Supply --output for a candidate")
    personal = args.personal_input or args.repo / "fixtures/legacy/Current/input.settings"
    raw = personal.read_bytes()
    outputs, receipt = prepare(args.repo, args.native_input, raw.decode("utf-8-sig"))
    receipt["personal_input_sha256"] = hashlib.sha256(raw).hexdigest()
    if args.check_runtime or args.sync_runtime:
        for relative, body in outputs.items():
            if not relative.startswith("src/"):
                continue
            target = args.repo / relative
            payload = body.encode("utf-8")
            if args.check_runtime:
                if target.read_bytes() != payload:
                    raise SchemeError("Missing or stale full-scheme runtime: " + relative)
            else:
                target.write_bytes(payload)
        print("PASS: full-scheme runtime sources and three-choice menu match pinned generation")
        return
    if args.output.exists():
        raise SchemeError("Candidate directory already exists")
    args.output.mkdir(parents=True)
    for relative, body in outputs.items():
        target = args.output / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(body.encode("utf-8"))
    (args.output / "candidate.json").write_text(json.dumps(receipt, indent=2) + "\n", encoding="utf-8")
    print(f"PASS: staged eight scripts, three-choice menu, {len(receipt['aliases'])} aliases; live files untouched")


if __name__ == "__main__":
    main()
